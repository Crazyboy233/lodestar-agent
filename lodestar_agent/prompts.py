def format_guidance(notes, for_whom: str = "规划") -> str:
    """把排队中的引导压成 prompt 里的一段；没有就是空串，prompt 结构不变。"""
    texts = [str(n.get("text", "")).strip() for n in notes or []]
    texts = [t for t in texts if t]
    if not texts:
        return ""
    body = "\n".join(f"- {t}" for t in texts)
    return (
        f"\n用户在你{for_whom}过程中插入的引导（优先级高于你自己的判断，但不要丢掉原有约束）：\n"
        f"{body}\n"
    )


def format_records_block(records: list[dict]) -> str:
    """给主 agent 看的进度：保留完整历史，让它能看到「这条失败过几次」。"""
    if not records:
        return "(暂无)"
    return "\n".join(
        f"- 子任务 {r['index']}: {r['task']} → {'通过' if r['passed'] else '未通过'}（{r['attempts']} 轮，{r['reason']}）"
        for r in records
    )
